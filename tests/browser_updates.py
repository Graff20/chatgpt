"""Optional browser acceptance scenarios for release 0.2."""
import os
import tempfile
import threading
import sys
from pathlib import Path
from datetime import datetime
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from app import Server
from demo import create_demo
from playwright.sync_api import sync_playwright,expect

with tempfile.TemporaryDirectory() as td:
    store=create_demo(Path(td)/'ceh.sqlite3')
    client=next(p for p in store.snapshot()['partners'] if p['kind']=='client')
    store.save_partner(dict(client,address='ул. Ленина, 15',phone='+7 900 111-22-33',contact='Анна Покупатель',debt_limit=100))
    server=Server(('127.0.0.1',0),td)
    thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start()
    try:
        with sync_playwright() as p:
            browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),headless=True,args=['--no-sandbox'])
            page=browser.new_page(viewport={'width':1500,'height':1100},locale='ru-RU')
            errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
            page.goto(f'http://127.0.0.1:{server.server_port}')
            expect(page.locator('h1')).to_have_text('Производство под контролем')
            page.locator('#employee').fill('Мария');page.locator('#employee').dispatch_event('change')
            page.locator('#nav a[href="#catalog"]').click()
            page.get_by_role('button',name='＋ Добавить позицию').click()
            page.locator('[name=name]').fill('Вода')
            page.locator('[name=unit]').select_option('л')
            expect(page.locator('[name=track_expiry]')).not_to_be_checked()
            expect(page.locator('[name=shelf_hours]')).to_be_disabled()
            page.locator('[name=track_expiry]').check()
            expect(page.locator('[name=shelf_hours]')).to_be_enabled()
            page.locator('[name=track_expiry]').uncheck()
            page.get_by_role('button',name='Сохранить',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            page.locator('#nav a[href="#stock"]').click()
            page.get_by_role('button',name='＋ Приёмка').click()
            page.locator('[name=partner_id]').select_option(label='Фермерский двор')
            page.locator('.r-item').select_option(label='Вода')
            expect(page.locator('.r-exp')).to_be_disabled()
            page.locator('.r-qty').fill('100');page.locator('.r-price').fill('5')
            page.get_by_role('button',name='Провести приёмку').click()
            expect(page.locator('#modal')).not_to_be_visible()
            expect(page.get_by_text('Без срока',exact=True)).to_be_visible()
            # Sender details are copied into the invoice.
            page.locator('#nav a[href="#settings"]').click()
            page.get_by_role('button',name='Реквизиты отправителя').click()
            page.locator('[name=name]').fill('Кондитерский цех')
            page.locator('[name=address]').fill('Адрес производства')
            page.locator('[name=phone]').fill('+7 900 999-88-77')
            page.get_by_role('button',name='Сохранить',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            # Register driver, then use the catalogue directly in the order.
            page.locator('#nav a[href="#logistics"]').click()
            page.get_by_role('button',name='＋ Водитель').click()
            page.locator('[name=name]').fill('Иван Водитель')
            page.locator('[name=phone]').fill('+7 900 222-33-44')
            page.locator('[name=vehicle]').fill('А123АА 77')
            page.get_by_role('button',name='Сохранить',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            page.locator('#nav a[href="#orders"]').click()
            page.get_by_role('button',name='＋ Новый заказ').click()
            page.locator('[name=client_id]').select_option(label=client['name'])
            expect(page.locator('[name=delivery_address]')).to_have_value('ул. Ленина, 15')
            expect(page.locator('[name=delivery_contact]')).to_have_value('Анна Покупатель')
            dt=datetime.now().replace(second=0,microsecond=0).isoformat(timespec='minutes')
            page.locator('[name=due]').fill(dt)
            page.locator('[name=driver_id]').select_option(label='Иван Водитель')
            page.locator('[name=route_position]').fill('1')
            page.locator('#order-lines .r-item').select_option(label='Куриное филе сувид')
            page.locator('#order-lines .r-qty').fill('1')
            page.get_by_role('button',name='Сохранить',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            ident=page.evaluate('Math.max(...S.orders.map(o=>o.id))')
            page.locator(f'[data-action="view-order"][data-id="{ident}"]').click()
            page.get_by_role('button',name='Отгрузить · уточнить вес').click()
            expect(page.locator('[name=sender_name]')).to_have_value('Кондитерский цех')
            expect(page.locator('[name=driver_id] option:checked')).to_have_text('Иван Водитель')
            page.locator('.s-qty').fill('1.037')
            page.locator('[name=discount_percent]').fill('10')
            expect(page.locator('#shipment-total')).to_contain_text('737,31')
            page.get_by_role('button',name='Провести отгрузку').click()
            expect(page.locator('#modal')).not_to_be_visible()  # Above limit 100, but today's money is still in transit.
            page.locator('#nav a[href="#documents"]').click()
            page.locator('[data-action="view-document"]').first.click()
            invoice=page.frame_locator('iframe')
            for text in ('Кондитерский цех','ул. Ленина, 15','Анна Покупатель','Иван Водитель','737,31'):
                expect(invoice.locator('body')).to_contain_text(text)
            docs=Path(__file__).resolve().parents[1]/'docs'
            print_page=browser.new_page(viewport={'width':1000,'height':1000},locale='ru-RU')
            print_page.goto(page.locator('iframe').get_attribute('src') if page.locator('iframe').get_attribute('src').startswith('http') else f'http://127.0.0.1:{server.server_port}'+page.locator('iframe').get_attribute('src'))
            print_page.screenshot(path=str(docs/'invoice.png'),full_page=True)
            print_page.close()
            page.locator('[data-action="close-modal"]').first.click()
            page.locator('#nav a[href="#logistics"]').click()
            page.locator('#logistics-driver').select_option(label='Иван Водитель')
            expect(page.locator('td').filter(has_text='Куриное филе сувид').first).to_be_visible()
            expect(page.get_by_text('ул. Ленина, 15',exact=False).first).to_be_visible()
            # Change delivery order independently after dispatch.
            page.locator('[data-action="assign-delivery"]').click()
            page.locator('[name=route_position]').fill('2')
            page.get_by_role('button',name='Сохранить',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            page.locator('#toast').wait_for(state='hidden',timeout=6000)
            page.screenshot(path=str(docs/'logistics.png'),full_page=True)
            with page.expect_download() as dl:page.locator('a[href*="type=route"][href*="format=xlsx"]').first.click()
            assert dl.value.suggested_filename.endswith('.xlsx')
            page.locator('#nav a[href="#finance"]').click()
            expect(page.get_by_text('К оплате сегодня',exact=True).first).to_be_visible()
            page.get_by_role('button',name='＋ Оплата клиента').click()
            page.locator('[name=partner_id]').select_option(label=client['name'])
            page.locator('[name=driver_id]').select_option(label='Иван Водитель')
            page.locator('[name=amount]').fill('600')
            page.get_by_role('button',name='Провести',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            page.get_by_role('button',name='Подвести итоги дня').click()
            page.get_by_role('button',name='Закрыть день',exact=True).click()
            expect(page.locator('#modal')).not_to_be_visible()
            expect(page.get_by_text('День закрыт',exact=True)).to_be_visible()
            debt=page.evaluate('S.partners.find(p=>p.kind==="client").debt')
            assert abs(debt-456.54)<.001,debt
            assert not errors,errors
            browser.close()
            print('Browser v2 passed: optional expiry, receipt, sender, driver, delivery address, discount, invoice, route, cashier payment, end-of-day debt.')
    finally:
        server.shutdown();server.server_close();thread.join()
